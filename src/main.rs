// BACnet Profile Example - B-SS (BACnet Smart Sensor) - Rust
//
// This example shows the *minimum* needed to implement the BACnet "B-SS"
// (Smart Sensor) device profile with the CAS BACnet Stack.
//
// A B-SS is "a simple sensing device with very limited resources" (ANSI/ASHRAE
// 135, Annex L.4.5). Its only mandatory capability is:
//
//     DS-RP-B  - respond to ReadProperty requests
//
// plus the ability to be discovered: it answers Who-Is with I-Am (handled
// automatically by the stack) and announces itself with an unsolicited I-Am on
// start-up.
//
// A B-SS does NOT require WriteProperty, COV, alarms/events, scheduling, or
// trending - so this example deliberately does NOT enable any of those. That is
// the whole point of a profile example: implement exactly what the profile
// asks for, nothing more.
//
// This is the Rust edition of BACnetProfileExample-B-SS-CPP / -CS / -Python -
// same objects, same names, same section layout, so you can diff the four side
// by side, and the FIRST Rust example in this series. The systematic
// difference here is the binding mechanism: Rust calls the native CAS BACnet
// Stack library through `libloading` (the vendored adapter in
// cas_bacnet_stack/, which does its own dlopen/GetProcAddress per call, like
// the C++ edition's explicit LoadBACnetFunctions() step - unlike C#, where the
// runtime resolves the library implicitly on first P/Invoke).
//
// THE ARCHITECTURAL CONSTRAINT THAT SHAPES THIS WHOLE FILE:
// BACnetStack_RegisterCallbackGetProperty*() takes `Option<extern "C" fn(...)>`
// - a plain, non-capturing function pointer, not a closure. So every
// Get*Property callback below is a free-standing `extern "C" fn` that reads
// device state from the `common::device_state::STATE` static (a
// `Lazy<Mutex<DeviceState>>`) rather than from a captured local - see
// device_state.rs's module doc for the full explanation. `main()` writes
// through that same lock (recording the discovered IP addressing at start-up;
// nudging the Analog Input from the interactive-command loop).
//
// PANIC SAFETY ACROSS THE FFI BOUNDARY. An unguarded Rust panic unwinding
// across an `extern "C" fn` callback into the C stack is undefined behavior.
// Every callback below wraps its body in `std::panic::catch_unwind` and
// returns `false` (leaving `errorCode` untouched - "no opinion", the same
// fallback a normal declining `return false` uses) on a caught panic, rather
// than letting it propagate. This stack has no CI-verified track record for
// Rust (its adapter carries its own "not compiled by any gate" warning - see
// cas_bacnet_stack/README.md), so defensive handling matters more here than in
// the other editions.
//
// The device exposes three read-only sensor objects plus the Network Port
// object that every BACnet device must have. Each object is given a colour name
// (a convention shared across this example series):
//
//     Device 389001          "Rainbow"    (instance configurable with --deviceID)
//     Analog Input  1        "Bronze"     (REAL, degrees Celsius; starts at 21.5)
//     Binary Input  1        "Emerald"    (active / inactive)
//     Multi-State Input 1    "Hot Pink"   (an enumerated state, 1..3)
//     Network Port 1         "Vermilion"  (the BACnet/IP port - required)
//
// To be a conformant BACnet device (Protocol_Revision 24) each object must
// expose its full set of REQUIRED properties. Most are generated by the stack
// (Object_Identifier, Object_Type, Status_Flags, Object_List, Protocol_*).
// Event_State is NOT generated - with no alarming configured it simply reads its
// datatype default of normal(0), correct by coincidence, not because the stack
// computes it. The handful that the application must supply are served by the
// Get*Property callbacks below, and a few are turned on with SetPropertyEnabled.
//
// Interactive commands (handled at the bottom of this file): a background
// thread reads LINE-buffered commands from stdin - h = help, q = quit,
// up/down = nudge Analog Input 1 by +/-1.1 - see "Interactive commands are a
// simplification" below for why this edition does not poll raw single
// keypresses like the C++/C#/Python editions. Command line: --port <n>,
// --deviceID <n>.
//
// All the UDP/stack plumbing lives in common/ so this file can stay focused on
// the BACnet logic.
// =============================================================================

