/// OCTET STRING - the Network Port's BACnet/IP addressing. The stack cannot
/// know the host's IP, so the application must supply IP_Address and
/// IP_Subnet_Mask (and IP_Default_Gateway). Each is four octets. The stack
/// also reads IP_Address (with BACnet_IP_UDP_Port) to build the port's
/// six-octet MAC_Address.
extern "C" fn get_property_octet_string(
    device_instance: u32,
    object_type: u16,
    object_instance: u32,
    property_identifier: u32,
    value: *mut u8,
    value_element_count: *mut u32,
    max_element_count: u32,
    _use_array_index: bool,
    _property_array_index: u32,
    _error_code: *mut u32,
) -> bool {
    catch_unwind(|| {
        let state = STATE.lock().unwrap_or_else(|e| e.into_inner());
        if device_instance != state.device_instance
            || object_type != c::OBJECT_TYPE_NETWORK_PORT
            || object_instance != c::NETWORK_PORT_INSTANCE
            || max_element_count < 4
        {
            return false;
        }
        let source = if property_identifier == c::PROPERTY_IDENTIFIER_IP_ADDRESS {
            state.ip_address
        } else if property_identifier == c::PROPERTY_IDENTIFIER_IP_SUBNET_MASK {
            state.ip_subnet_mask
        } else if property_identifier == c::PROPERTY_IDENTIFIER_IP_DEFAULT_GATEWAY {
            state.ip_default_gateway
        } else {
            return false;
        };
        unsafe {
            for i in 0..4 {
                *value.add(i) = source[i];
            }
            *value_element_count = 4;
        }
        true
    })
    .unwrap_or(false)
}

/// Copy a `&str` into the stack's character-string buffer as UTF-8 and set
/// the element count + encoding. SAFETY: caller guarantees `value` has room
/// for at least `max_element_count` bytes.
unsafe fn write_character_string(
    text: &str,
    value: *mut c_char,
    value_element_count: *mut u32,
    max_element_count: u32,
    encoding_type: *mut u8,
) -> bool {
    let mut bytes = text.as_bytes();
    if bytes.len() as u32 > max_element_count {
        // Truncate SILENTLY to fit the stack's buffer. max_element_count is
        // MAX_CHARACTER_STRING_SIZE (256 in this build), and our longest
        // string (DEVICE_DESCRIPTION) fits with room to spare - so this never
        // trips here. But if you build with a smaller embedded buffer, that
        // limit drops, and a long Object_Name or Description would be clipped
        // mid-word with nothing on the wire or console to tell you. If you
        // lengthen any served string, check it against
        // MAX_CHARACTER_STRING_SIZE for your target, or make this truncation
        // loud.
        bytes = &bytes[..max_element_count as usize];
    }
    for (i, b) in bytes.iter().enumerate() {
        *value.add(i) = *b as c_char;
    }
    *value_element_count = bytes.len() as u32;
    *encoding_type = c::CHARACTER_STRING_ENCODING_UTF8;
    true
}

/// CHARACTER STRING - Object_Name for each object, and the device Description.
extern "C" fn get_property_character_string(
    device_instance: u32,
    object_type: u16,
    object_instance: u32,
    property_identifier: u32,
    value: *mut c_char,
    value_element_count: *mut u32,
    max_element_count: u32,
    encoding_type: *mut u8,
    use_array_index: bool,
    property_array_index: u32,
    error_code: *mut u32,
) -> bool {
    catch_unwind(|| {
        let state = STATE.lock().unwrap_or_else(|e| e.into_inner());
        if device_instance != state.device_instance {
            return false;
        }

        // State_Text (optional) - one label per state of the Multi-State
        // Input. It is a BACnet array, so the stack asks for one element at
        // a time by index (1..Number_Of_States). Present_Value 1 -> "On",
        // 2 -> "Off", 3 -> "Auto".
        if object_type == c::OBJECT_TYPE_MULTI_STATE_INPUT
            && object_instance == MULTI_STATE_INPUT_INSTANCE
            && property_identifier == c::PROPERTY_IDENTIFIER_STATE_TEXT
            && use_array_index
        {
            if (1..=MULTI_STATE_INPUT_NUMBER_OF_STATES).contains(&property_array_index) {
                return unsafe {
                    write_character_string(
                        MULTI_STATE_TEXT[(property_array_index - 1) as usize],
                        value,
                        value_element_count,
                        max_element_count,
                        encoding_type,
                    )
                };
            }
            // The one place in this file where naming an error is clearly
            // right: the client asked for State_Text[n] and this object has
            // no element n. That is not "no opinion" - it is a wrong read,
            // and the spec has a code for it. Without this the client would
            // silently receive an empty string.
            unsafe { *error_code = c::ERROR_CODE_INVALID_ARRAY_INDEX };
            return false;
        }

        // Object_Name - the colour name for each object.
        if property_identifier == c::PROPERTY_IDENTIFIER_OBJECT_NAME {
            let name = if object_type == c::OBJECT_TYPE_DEVICE && object_instance == state.device_instance {
                Some(DEVICE_NAME)
            } else if object_type == c::OBJECT_TYPE_ANALOG_INPUT && object_instance == ANALOG_INPUT_INSTANCE {
                Some("Bronze")
            } else if object_type == c::OBJECT_TYPE_BINARY_INPUT && object_instance == BINARY_INPUT_INSTANCE {
                Some("Emerald")
            } else if object_type == c::OBJECT_TYPE_MULTI_STATE_INPUT
                && object_instance == MULTI_STATE_INPUT_INSTANCE
            {
                Some("Hot Pink")
            } else if object_type == c::OBJECT_TYPE_NETWORK_PORT && object_instance == c::NETWORK_PORT_INSTANCE {
                Some("Vermilion")
            } else {
                None
            };
            if let Some(name) = name {
                return unsafe {
                    write_character_string(name, value, value_element_count, max_element_count, encoding_type)
                };
            }
        }

        // The remaining strings are all on the Device object - its identity,
        // read by clients and used to populate the device's I-Am / object
        // list.
        if object_type == c::OBJECT_TYPE_DEVICE && object_instance == state.device_instance {
            let text = if property_identifier == c::PROPERTY_IDENTIFIER_DESCRIPTION {
                Some(DEVICE_DESCRIPTION)
            } else if property_identifier == c::PROPERTY_IDENTIFIER_VENDOR_NAME {
                Some(VENDOR_NAME)
            } else if property_identifier == c::PROPERTY_IDENTIFIER_MODEL_NAME {
                Some(MODEL_NAME)
            } else if property_identifier == c::PROPERTY_IDENTIFIER_FIRMWARE_REVISION {
                Some(FIRMWARE_REVISION)
            } else if property_identifier == c::PROPERTY_IDENTIFIER_APPLICATION_SOFTWARE_VERSION {
                Some(APPLICATION_SOFTWARE_VERSION)
            } else {
                None
            };
            if let Some(text) = text {
                return unsafe {
                    write_character_string(text, value, value_element_count, max_element_count, encoding_type)
                };
            }
        }

        false
    })
    .unwrap_or(false)
}

// -----------------------------------------------------------------------------
// 3. Interactive commands are a simplification - see TUTORIAL.md
// -----------------------------------------------------------------------------
// The C++ edition polls raw console keys (including arrow-key escape
// sequences) every millisecond in its own loop. The C# edition uses .NET's
// built-in non-blocking Console.KeyAvailable/ReadKey. The Python edition picks
// a platform-appropriate raw-mode poller (msvcrt on Windows, termios/tty/select
// on POSIX). Rust's standard library has NO non-blocking single-keypress read
// on any platform - that needs a platform-specific crate (e.g. `crossterm`),
// which this example deliberately avoids to keep the dependency list to
// exactly `libloading`/`once_cell`/`ctrlc` (see Cargo.toml).
//
// So this edition reads LINE-buffered commands instead: type a command and
// press Enter. A background thread blocks on stdin's `read_line()` (there is
// no portable way to make that non-blocking in std either) and forwards
// completed commands to the main loop over an `mpsc` channel, which the main
// loop drains without blocking (`try_recv()`) once per tick. This also means
// there is no TTY check to skip: a background/piped run (the CI smoke test,
// for instance) simply sees stdin hit EOF immediately, the reader thread
// exits quietly, and the device keeps running - Ctrl+C still works via the
// handler below.
// -----------------------------------------------------------------------------

enum Command {
    Help,
    Quit,
    Up,
    Down,
}

fn spawn_command_reader() -> mpsc::Receiver<Command> {
    let (tx, rx) = mpsc::channel();
    std::thread::spawn(move || {
        let stdin = std::io::stdin();
        loop {
            let mut line = String::new();
            match stdin.read_line(&mut line) {
                Ok(0) => break, // EOF - not an interactive console (or it closed)
                Ok(_) => {
                    let command = match line.trim().to_ascii_lowercase().as_str() {
                        "h" | "help" => Some(Command::Help),
                        "q" | "quit" => Some(Command::Quit),
                        "up" | "u" => Some(Command::Up),
                        "down" | "d" => Some(Command::Down),
                        _ => None,
                    };
                    if let Some(command) = command {
                        if tx.send(command).is_err() {
                            break; // main loop has exited
                        }
                    }
                }
                Err(_) => break,
            }
        }
    });
    rx
}

fn print_help() {
    cas_example_helper::print_version(APP_NAME, APP_VERSION);
    println!("Commands (type + Enter): h = this help, q = quit, up/down = Analog Input 1 +/- 1.1");
}

