// 4. main()
// -----------------------------------------------------------------------------

fn parse_args() -> Result<(u16, u32), i32> {
    let mut port: u16 = 47808;
    let mut device_id: u32 = 389001;
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--help" | "-h" => {
                println!("{APP_NAME}");
                println!("Options:");
                println!("  --help              Show this help and exit");
                println!("  --version           Show version information and exit");
                println!("  --deviceID <inst>   BACnet Device instance (0..4194302, default 389001)");
                println!("  --port <n>          BACnet/IP UDP port to listen on (default 47808)");
                return Err(0);
            }
            "--version" => {
                // Printed by the caller once the library is confirmed loadable.
                return Err(-1); // sentinel: "print version and exit 0"
            }
            "--port" => {
                i += 1;
                let raw = args.get(i).map(String::as_str).unwrap_or("");
                match cas_example_helper::parse_port(raw) {
                    Ok(v) => port = v,
                    Err(e) => {
                        eprintln!("Error: {e}");
                        return Err(1);
                    }
                }
            }
            "--deviceID" => {
                i += 1;
                let raw = args.get(i).map(String::as_str).unwrap_or("");
                match cas_example_helper::parse_device_id(raw) {
                    Ok(v) => device_id = v,
                    Err(e) => {
                        eprintln!("Error: {e}");
                        return Err(1);
                    }
                }
            }
            other => {
                eprintln!("Error: unrecognized argument \"{other}\" (see --help)");
                return Err(1);
            }
        }
        i += 1;
    }
    Ok((port, device_id))
}

fn main() -> std::process::ExitCode {
    let (port, device_id, want_version_only) = match parse_args() {
        Ok((p, d)) => (p, d, false),
        Err(-1) => (47808, 389001, true),
        Err(0) => return std::process::ExitCode::SUCCESS,
        Err(_) => return std::process::ExitCode::FAILURE,
    };

    {
        let mut state = STATE.lock().unwrap_or_else(|e| e.into_inner());
        state.device_instance = device_id;
    }

    // --- Load the CAS BACnet Stack + print version ----------------------------
    // Unlike the C# edition (where the runtime resolves the native library
    // implicitly on first P/Invoke), this is an explicit load step like the
    // C++/Python editions: the first call into `bacnet::` forces the
    // `once_cell::sync::Lazy<libloading::Library>` in
    // cas_bacnet_stack_adapters.rs, which panics with a descriptive message if
    // the library cannot be found (see that file's `load_library()` for the
    // search order this vendored copy uses). Catch that panic here so a
    // missing/mismatched native library is reported the same way the other
    // editions report it, instead of a raw Rust panic backtrace.
    let version_result = catch_unwind(|| {
        cas_example_helper::print_version(APP_NAME, APP_VERSION);
    });
    if version_result.is_err() {
        eprintln!("Error: failed to load the CAS BACnet Stack native library.");
        eprintln!(
            "Copy CASBACnetStack_x64_Release.dll (Windows) / libCASBACnetStack_x64_Release.so (Linux) \
             next to this executable - see README.md \"Build the native CAS BACnet Stack library\"."
        );
        return std::process::ExitCode::FAILURE;
    }
    if want_version_only {
        return std::process::ExitCode::SUCCESS;
    }

    // --- Bind the BACnet/IP socket -------------------------------------------
    if let Err(e) = cas_example_helper::setup_udp(port) {
        eprintln!("Error: could not bind UDP port {port}: {e}");
        eprintln!("Is another BACnet device already running on this machine? Try --port.");
        return std::process::ExitCode::FAILURE;
    }

    // Capture the BACnet/IP addressing the Network Port object will report.
    let local = cas_example_helper::get_local_ipv4();
    {
        let mut state = STATE.lock().unwrap_or_else(|e| e.into_inner());
        state.bacnet_ip_udp_port = port;
        state.ip_address = local.address.octets();
        state.ip_subnet_mask = local.netmask.octets();
    }
    println!("FYI: listening on {}:{port} (broadcast {})", local.address, local.broadcast);

    // --- Register callbacks ---------------------------------------------------
    // The transport + time callbacks are shared boilerplate, keyed to
    // common::constants::NETWORK_PORT_INSTANCE.
    cas_example_helper::register_common_callbacks();

    // The property callbacks are specific to this example.
    let ok = bacnet::BACnetStack_RegisterCallbackGetPropertyReal(Some(get_property_real)).is_ok()
        && bacnet::BACnetStack_RegisterCallbackGetPropertyEnumerated(Some(get_property_enumerated)).is_ok()
        && bacnet::BACnetStack_RegisterCallbackGetPropertyUnsignedInteger(Some(get_property_unsigned_integer))
            .is_ok()
        && bacnet::BACnetStack_RegisterCallbackGetPropertyCharacterString(Some(get_property_character_string))
            .is_ok()
        && bacnet::BACnetStack_RegisterCallbackGetPropertyBool(Some(get_property_bool)).is_ok()
        && bacnet::BACnetStack_RegisterCallbackGetPropertyOctetString(Some(get_property_octet_string)).is_ok();
    if !ok {
        eprintln!("Error: failed to register one or more Get*Property callbacks.");
        return std::process::ExitCode::FAILURE;
    }

    // --- Create the device -----------------------------------------------------
    if !bacnet::BACnetStack_AddDevice(device_id).unwrap_or(false) {
        eprintln!("Error: Failed to add the Device {device_id}.");
        return std::process::ExitCode::FAILURE;
    }

    // Enable ReadProperty (DS-RP-B) - the one mandatory service for B-SS. We
    // set it explicitly to make the profile requirement obvious.
    //
    // We deliberately do NOT enable WriteProperty, ReadPropertyMultiple,
    // SubscribeCOV, or any alarm/event service: a Smart Sensor does not
    // require them, so a faithful B-SS example leaves them off.
    if !bacnet::BACnetStack_SetServiceEnabled(device_id, c::SERVICE_READ_PROPERTY, true).unwrap_or(false) {
        eprintln!("Error: Failed to enable the ReadProperty service.");
        return std::process::ExitCode::FAILURE;
    }

    // Discovery: Who-Is/I-Am (DM-DDB-B) and Who-Has/I-Have (DM-DOB-B).
    //
    // These need enabling even though the device already ANSWERS them. The
    // stack's service defaults are whoIs + whoHas + readProperty only - iAm
    // and iHave are left false. Who-Is is answered and the start-up I-Am is
    // sent regardless, because neither is gated on the bit; but
    // Protocol_Services_Supported is emitted verbatim from that bitstring, so
    // without these calls the device DOES I-Am and I-Have while telling every
    // client it supports neither.
    let discovery_ok = bacnet::BACnetStack_SetServiceEnabled(device_id, c::SERVICE_WHO_IS, true).unwrap_or(false)
        && bacnet::BACnetStack_SetServiceEnabled(device_id, c::SERVICE_I_AM, true).unwrap_or(false)
        && bacnet::BACnetStack_SetServiceEnabled(device_id, c::SERVICE_WHO_HAS, true).unwrap_or(false)
        && bacnet::BACnetStack_SetServiceEnabled(device_id, c::SERVICE_I_HAVE, true).unwrap_or(false);
    if !discovery_ok {
        eprintln!("Error: Failed to enable the discovery services (Who-Is/I-Am, Who-Has/I-Have).");
        return std::process::ExitCode::FAILURE;
    }

    // --- Add the read-only sensor objects ---------------------------------------
    if !bacnet::BACnetStack_AddObject(device_id, c::OBJECT_TYPE_ANALOG_INPUT, ANALOG_INPUT_INSTANCE)
        .unwrap_or(false)
    {
        eprintln!("Error: Failed to add Analog Input {ANALOG_INPUT_INSTANCE} (Bronze).");
        return std::process::ExitCode::FAILURE;
    }
    if !bacnet::BACnetStack_AddObject(device_id, c::OBJECT_TYPE_BINARY_INPUT, BINARY_INPUT_INSTANCE)
        .unwrap_or(false)
    {
        eprintln!("Error: Failed to add Binary Input {BINARY_INPUT_INSTANCE} (Emerald).");
        return std::process::ExitCode::FAILURE;
    }
    if !bacnet::BACnetStack_AddObject(device_id, c::OBJECT_TYPE_MULTI_STATE_INPUT, MULTI_STATE_INPUT_INSTANCE)
        .unwrap_or(false)
    {
        eprintln!("Error: Failed to add Multi-State Input {MULTI_STATE_INPUT_INSTANCE} (Hot Pink).");
        return std::process::ExitCode::FAILURE;
    }

    // --- Add the Network Port object --------------------------------------------
    // Every BACnet device (Protocol_Revision 17+) must have at least one
    // Network Port object describing the port it talks on. This one is the
    // BACnet/IP application port; it is the lowest layer, so its reference
    // port is "none". networkNumber 0 with quality "unknown" describes a
    // local port that has not learned its network number - the right answer
    // for a device that is not a router and has not been told one.
    if !bacnet::BACnetStack_AddNetworkPortObject(
        device_id,
        c::NETWORK_PORT_INSTANCE,
        c::NETWORK_PORT_NETWORK_TYPE_IPV4,
        c::NETWORK_PORT_PROTOCOL_LEVEL_BACNET_APPLICATION,
        0, // networkNumber: not configured
        c::NETWORK_NUMBER_QUALITY_UNKNOWN,
        c::NETWORK_PORT_REFERENCE_PORT_NONE,
    )
    .unwrap_or(false)
    {
        eprintln!("Error: Failed to add Network Port 1 (Vermilion).");
        return std::process::ExitCode::FAILURE;
    }

    // --- Enable the OPTIONAL properties we choose to expose ---------------------
    // The stack automatically enables an object's REQUIRED properties when the
    // object is added - so Units, Polarity, Number_Of_States, Out_Of_Service,
    // and the Network Port's BACnet/IP addressing are already enabled; our
    // Get* callbacks just supply their values. Only OPTIONAL properties need
    // SetPropertyEnabled. State_Text is optional on a Multi-State Input, so we
    // enable it here (and serve it in get_property_character_string).
    //
    // The Device's Description is optional too, and it is an easy one to get
    // wrong: serving it from a Get callback is NOT enough. The stack checks
    // IsPropertyEnabled BEFORE it ever reaches the callbacks, and for an
    // optional property that check falls back to "is it required?" - which is
    // false. So a Description branch in the callback without this enable is
    // DEAD CODE, and the client reads back Error: unknown-property.
    if !bacnet::BACnetStack_SetPropertyEnabled(
        device_id,
        c::OBJECT_TYPE_DEVICE,
        device_id,
        c::PROPERTY_IDENTIFIER_DESCRIPTION,
        true,
    )
    .unwrap_or(false)
    {
        eprintln!("Error: Failed to enable Description on the Device object.");
        return std::process::ExitCode::FAILURE;
    }
    if !bacnet::BACnetStack_SetPropertyEnabled(
        device_id,
        c::OBJECT_TYPE_MULTI_STATE_INPUT,
        MULTI_STATE_INPUT_INSTANCE,
        c::PROPERTY_IDENTIFIER_STATE_TEXT,
        true,
    )
    .unwrap_or(false)
    {
        eprintln!("Error: Failed to enable State_Text on Multi-State Input 1 (Hot Pink).");
        return std::process::ExitCode::FAILURE;
    }

    // Who-Is is answered automatically. The spec also requires a device to
    // announce itself on start-up, so broadcast an unsolicited I-Am now (to
    // the local subnet broadcast - the Network Port's own network).
    if !cas_example_helper::send_i_am(device_id, port) {
        eprintln!("Error: SendIAm failed.");
        return std::process::ExitCode::FAILURE;
    }

    println!("FYI: Device {device_id} (\"{DEVICE_NAME}\") ready. Vendor ID {VENDOR_IDENTIFIER}. Type 'h' + Enter for help.");

    // --- Graceful Ctrl+C shutdown ------------------------------------------------
    let running = Arc::new(AtomicBool::new(true));
    {
        let running = Arc::clone(&running);
        // ctrlc is the simplest reliable cross-platform SIGINT/Ctrl+C hook
        // available without hand-rolling per-OS signal handling (POSIX
        // sigaction vs. Windows SetConsoleCtrlHandler) - see Cargo.toml.
        ctrlc::set_handler(move || {
            running.store(false, Ordering::SeqCst); // handle it ourselves instead of the process dying mid-tick
        })
        .expect("failed to install the Ctrl+C handler");
    }

    let commands = spawn_command_reader();

    // --- Run the stack -------------------------------------------------------------
    // BACnetStack_Tick() processes incoming messages and timers. Call it
    // continuously, and drain any completed interactive command. The stack is
    // single-threaded by contract - everything that touches it happens on this
    // one loop; the reader thread only ever sends completed Command values
    // over the channel, never calls into the stack itself.
    while running.load(Ordering::SeqCst) {
        let _ = bacnet::BACnetStack_Tick();

        match commands.try_recv() {
            Ok(Command::Help) => print_help(),
            Ok(Command::Quit) => running.store(false, Ordering::SeqCst),
            Ok(Command::Up) => {
                let mut state = STATE.lock().unwrap_or_else(|e| e.into_inner());
                state.analog_input_1_value += 1.1;
                println!("Analog Input 1 (Bronze) = {:.1} C", state.analog_input_1_value);
            }
            Ok(Command::Down) => {
                let mut state = STATE.lock().unwrap_or_else(|e| e.into_inner());
                state.analog_input_1_value -= 1.1;
                println!("Analog Input 1 (Bronze) = {:.1} C", state.analog_input_1_value);
            }
            Err(_) => {} // nothing waiting this tick
        }

        std::thread::sleep(Duration::from_millis(1)); // be a good citizen, don't spin the CPU
    }

    cas_example_helper::shutdown_udp();
    println!("FYI: stopped.");
    std::process::ExitCode::SUCCESS
}
