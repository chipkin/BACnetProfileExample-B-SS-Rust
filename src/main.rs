// -----------------------------------------------------------------------------
// 2. Property "get" callbacks
//
// The stack calls these when a client reads a property. For each data type the
// stack uses a separate callback. We return true (and fill *value) when we
// recognise the (object, property) pair, and false otherwise.
//
// THE errorCode OUT-PARAMETER. Every Get callback ends with a trailing
// errorCode pointer. The stack PRESETS it to success (84) before the call, and
// reads it only if we return false. That gives a declining callback two
// distinct meanings:
//
//   1. return false and LEAVE *errorCode ALONE -> "I have no opinion on this
//      property." The stack falls back to its own handling (see below).
//   2. return false and SET *errorCode          -> "This read fails, with THIS
//      BACnet error." The client gets exactly that Error-PDU.
//
// WHAT false-WITHOUT-AN-ERROR-CODE ACTUALLY DOES - the most important
// paragraph in this file, and the opposite of what most people assume. It
// does NOT reliably produce a BACnet error. The stack errors only for the
// handful of properties it refuses to invent: Present_Value,
// Number_Of_States, Relinquish_Default, Local_Date, Local_Time, and a Network
// Port's APDU_Length. For EVERYTHING ELSE, a false return means the stack
// SILENTLY SUBSTITUTES a default:
//     Object_Name -> the literal string "undefined"
//     Units       -> no-units (95)
//     otherwise   -> a datatype zero-value
//
// AND THAT FALLBACK IS LORE-BEARING, WHICH IS WHY WE DO NOT "FIX" IT HERE. The
// stack relies on the decline-and-fabricate path to answer required
// properties the application is not expected to serve - the Device's
// Max_APDU_Length_Accepted, APDU_Timeout and Number_Of_APDU_Retries among
// them. Set *errorCode ONLY where THIS device knows the read is wrong. There
// is exactly one such case below (State_Text with an out-of-range array
// index); the catch-all `return false` at the end of each callback
// deliberately leaves *errorCode alone.
//
// ADDING AN OBJECT? See TUTORIAL.md "Add a second analog input" before you
// do - a half-added object does NOT fail loudly (see above).
// -----------------------------------------------------------------------------

/// REAL (floating point) - the Analog Input's Present_Value.
extern "C" fn get_property_real(
    device_instance: u32,
    object_type: u16,
    object_instance: u32,
    property_identifier: u32,
    value: *mut f32,
    _use_array_index: bool,
    _property_array_index: u32,
    _error_code: *mut u32,
) -> bool {
    catch_unwind(|| {
        let state = STATE.lock().unwrap_or_else(|e| e.into_inner());
        if device_instance == state.device_instance
            && object_type == c::OBJECT_TYPE_ANALOG_INPUT
            && object_instance == ANALOG_INPUT_INSTANCE
            && property_identifier == c::PROPERTY_IDENTIFIER_PRESENT_VALUE
        {
            // ON REAL HARDWARE: return the live sensor reading here. Read it
            // from a cached variable that your hardware updates (as
            // state.analog_input_1_value is), NOT directly from a
            // slow/blocking device (I2C, SPI, ADC conversion): this callback
            // runs on the BACnetStack_Tick() call, so blocking it delays all
            // BACnet processing. Sample the sensor on a timer/another thread
            // and just hand back the latest value from here.
            // SAFETY: `value` is a valid, aligned, writable f32 out-param for
            // the duration of this call, per the stack's documented contract.
            unsafe { *value = state.analog_input_1_value };
            true
        } else {
            false
        }
    })
    .unwrap_or(false)
}

/// ENUMERATED - the Binary Input's Present_Value (0 = inactive, 1 = active),
/// the Analog Input's Units, and the Network Port's BACnet_IP_Mode.
extern "C" fn get_property_enumerated(
    device_instance: u32,
    object_type: u16,
    object_instance: u32,
    property_identifier: u32,
    value: *mut u32,
    _use_array_index: bool,
    _property_array_index: u32,
    _error_code: *mut u32,
) -> bool {
    catch_unwind(|| {
        let state = STATE.lock().unwrap_or_else(|e| e.into_inner());
        if device_instance != state.device_instance {
            return false;
        }
        if object_type == c::OBJECT_TYPE_BINARY_INPUT && object_instance == BINARY_INPUT_INSTANCE {
            if property_identifier == c::PROPERTY_IDENTIFIER_PRESENT_VALUE {
                // ON REAL HARDWARE: return your cached input state here - the
                // same rule as get_property_real above applies.
                unsafe { *value = BINARY_INPUT_1_VALUE };
                return true;
            }
            if property_identifier == c::PROPERTY_IDENTIFIER_POLARITY {
                unsafe { *value = c::POLARITY_NORMAL }; // required property of a Binary Input
                return true;
            }
        }
        if object_type == c::OBJECT_TYPE_ANALOG_INPUT
            && object_instance == ANALOG_INPUT_INSTANCE
            && property_identifier == c::PROPERTY_IDENTIFIER_UNITS
        {
            unsafe { *value = c::ENGINEERING_UNITS_DEGREES_CELSIUS };
            return true;
        }
        if object_type == c::OBJECT_TYPE_NETWORK_PORT
            && object_instance == c::NETWORK_PORT_INSTANCE
            && property_identifier == c::PROPERTY_IDENTIFIER_BACNET_IP_MODE
        {
            unsafe { *value = c::BACNET_IP_MODE_NORMAL }; // not foreign-device, not BBMD
            return true;
        }
        false
    })
    .unwrap_or(false)
}

/// UNSIGNED INTEGER - the Multi-State Input's Present_Value, and the Device's
/// Vendor_Identifier (the stack also uses Vendor_Identifier to build I-Am).
extern "C" fn get_property_unsigned_integer(
    device_instance: u32,
    object_type: u16,
    object_instance: u32,
    property_identifier: u32,
    value: *mut u32,
    use_array_index: bool,
    property_array_index: u32,
    _error_code: *mut u32,
) -> bool {
    catch_unwind(|| {
        let state = STATE.lock().unwrap_or_else(|e| e.into_inner());
        if device_instance != state.device_instance {
            return false;
        }
        if object_type == c::OBJECT_TYPE_MULTI_STATE_INPUT && object_instance == MULTI_STATE_INPUT_INSTANCE {
            if property_identifier == c::PROPERTY_IDENTIFIER_PRESENT_VALUE {
                unsafe { *value = MULTI_STATE_INPUT_1_VALUE }; // valid range is 1..Number_Of_States
                return true;
            }
            if property_identifier == c::PROPERTY_IDENTIFIER_NUMBER_OF_STATES {
                unsafe { *value = MULTI_STATE_INPUT_NUMBER_OF_STATES }; // required property
                return true;
            }
            // State_Text is an array. The stack asks for its LENGTH here
            // (array index 0) before reading each element via
            // get_property_character_string.
            if property_identifier == c::PROPERTY_IDENTIFIER_STATE_TEXT
                && use_array_index
                && property_array_index == 0
            {
                unsafe { *value = MULTI_STATE_INPUT_NUMBER_OF_STATES };
                return true;
            }
        }
        if object_type == c::OBJECT_TYPE_DEVICE
            && object_instance == state.device_instance
            && property_identifier == c::PROPERTY_IDENTIFIER_VENDOR_IDENTIFIER
        {
            unsafe { *value = VENDOR_IDENTIFIER };
            return true;
        }
        if object_type == c::OBJECT_TYPE_NETWORK_PORT && object_instance == c::NETWORK_PORT_INSTANCE {
            if property_identifier == c::PROPERTY_IDENTIFIER_APDU_LENGTH {
                unsafe { *value = MAX_APDU_LENGTH };
                return true;
            }
            if property_identifier == c::PROPERTY_IDENTIFIER_REFERENCE_PORT {
                unsafe { *value = c::NETWORK_PORT_REFERENCE_PORT_NONE };
                return true;
            }
            if property_identifier == c::PROPERTY_IDENTIFIER_BACNET_IP_UDP_PORT {
                unsafe { *value = state.bacnet_ip_udp_port as u32 };
                return true;
            }
        }
        false
    })
    .unwrap_or(false)
}

